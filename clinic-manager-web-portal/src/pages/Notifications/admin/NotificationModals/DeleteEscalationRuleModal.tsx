import { CommonButton, CommonIcon, Modal } from "@/components/common";
import { toast } from "@/utils/toast";
import { Box, Typography, useTheme } from "@mui/material";
import { useEscalationRule } from "../../hooks/useEditEscalation";

interface EscalationRuleModalProps {
  open: boolean;
  onClose: () => void;
  ruleId: string | null;
  ruleName?: string;
  onDeleteSuccess: () => void;
}

export default function DeleteEscalationRuleModal({
  open,
  onClose,
  ruleId,
  ruleName,
  onDeleteSuccess,
}: EscalationRuleModalProps) {
  const theme = useTheme();

  const { deleteEscalationRule, deleting } = useEscalationRule(
    ruleId || undefined
  );

  const handleDelete = async () => {
    if (!ruleId) return;

    try {
      await deleteEscalationRule();
      toast.success("Escalation rule deleted successfully");
      onDeleteSuccess();
      onClose();
    } catch (error) {
      toast.error("Failed to delete escalation rule");
      console.error("Delete error:", error);
    }
  };

  return (
    <Modal open={open} onClose={onClose}>
      <Box
        sx={{
          display: "flex",
          flexDirection: "column",
          alignItems: "center",
          textAlign: "center",
          gap: "24px",
          margin: "0 auto",
        }}
      >
        <Typography
          variant="h3"
          fontWeight={600}
          color={theme.palette.text.primary}
        >
          Delete Escalation Rule?
        </Typography>
        <Box
          sx={{
            width: 80,
            height: 80,
            borderRadius: "50%",
            border: `2px solid ${theme.palette.primary.main}`,
            bgcolor: "#FEFBF1",
            display: "flex",
            justifyContent: "center",
            alignItems: "center",
          }}
        >
          <CommonIcon
            name="Trash2"
            size={46}
            color={theme.palette.primary.main}
          />
        </Box>

        <Typography variant="body1" color={theme.palette.text.secondary}>
          You are about to delete "{ruleName}"
        </Typography>

        <Box
          sx={{
            p: 2.5,
            borderRadius: "12px",
            bgcolor: "#FDECEA",
            border: "1px solid #F5C2C7",
          }}
        >
          {/* Header */}
          <Box sx={{ display: "flex", alignItems: "center", gap: 1, mb: 1.5 }}>
            <CommonIcon name="AlertTriangle" color="red" size={20} />
            <Typography sx={{ color: "error.main", fontWeight: 700 }}>
              Warning
            </Typography>
          </Box>
          <Typography
            sx={{
              display: "flex",
              flexDirection: "column",
              color: "error.dark",
              fontSize: 15,
              lineHeight: 1.4,
            }}
          >
            This will stop all alerts generated by this rule immediately. This
            action is permanent.
          </Typography>
        </Box>

        <Box sx={{ width: "100%", mt: 1 }}>
          <CommonButton
            fullWidth
            variant="contained"
            color="error"
            loading={deleting}
            onClick={handleDelete}
            disabled={deleting}
          >
            Delete Rule
          </CommonButton>

          {/* CANCEL BUTTON */}
          <CommonButton
            fullWidth
            variant="outlined"
            sx={{
              mt: 2,
            }}
            disabled={deleting}
            onClick={onClose}
          >
            Cancel
          </CommonButton>
        </Box>
      </Box>
    </Modal>
  );
}
